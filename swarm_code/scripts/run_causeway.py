#!/usr/bin/env python3
"""Run frozen m3 causeway detector on m2 v3 products without hiding canopy.

  .venv/bin/python code/run_causeway.py data/derived_v2/0414

All finite DTM cells outside original no-return holes are tested. The more
restrictive open-canopy detector mask is not required; canopy remains evidence
for skeptical review. Coordinates stay local and lon/lat are regenerated by the
record audit from native EPSG x/y.
"""
from pathlib import Path
import argparse
import json
import sys
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "code/vendor_causeway"))
import load_m2
import run_transect as R


def main():
    p = argparse.ArgumentParser()
    p.add_argument("derived", type=Path)
    args = p.parse_args()
    transect = args.derived.name
    out, meta, summary = load_m2.load(args.derived)
    z, chm = out["dtm"], out["chm"]
    valid = np.isfinite(z) & ~out["mask_data_hole"]
    result = R.run((z, meta), transect, str(args.derived / "causeway"),
                   block_m=1200, overlap_m=120, mask=valid, chm_array=chm)
    result["validity_rule"] = ("finite v3 DTM outside original no-return holes; "
                               "do not silently exclude tall canopy")
    (args.derived / "causeway" / transect / "validity.json").write_text(
        json.dumps({"rule": result["validity_rule"], "cells": int(valid.sum())}, indent=2) + "\n")
    print(f"Causeway complete {transect}: {result['n_candidates']} raised linear features; "
          f"{result['n_causeway']} classified causeway")


if __name__ == "__main__":
    main()
