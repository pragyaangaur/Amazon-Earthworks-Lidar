"""Provenance sheet: what is actually in the workspace, verified locally.

Writes a Markdown sheet with the size and SHA-256 of every input the record check
relies on, the citation details that can be read from the release's own
CITATION.cff/README.md, the toolchain versions, and the dead ends that were
checked so nobody repeats them (the published predictive model cannot be opened
offline).  No network: everything is read from local files.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

INPUTS = [
    ("data/known/peripato/Earthworks.rds", "known-earthwork table, 961 records (Peripato et al. 2023 release)"),
    ("data/known/earthworks.csv", "coordinator's CSV conversion of the same table"),
    ("data/footprints/transectos_total_v20210616.shp", "EBA L3A transect footprints, 901 polygons"),
    ("data/footprints/transectos_total_v20210616.dbf", "footprint attributes (transect id, per-tile CRS)"),
    ("data/footprints/transectos_total_v20210616.prj", "footprint CRS, parses to EPSG:5880"),
    ("data/footprints/transect_ids.json", "coordinator's transect id list (901)"),
    ("data/downloads/ade2541-v1.0.0.zip", "Peripato et al. data release archive"),
    ("data/downloads/L3A_transects_v20210616.zip", "L3A footprint archive"),
    (".scratch/amazon/raw/NP_T-0414.laz", "raw LAZ for the 0414 positive control (coordinator-managed)"),
]

CITATION_KEYS = ("title", "doi", "url", "year", "version", "publisher")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def read_citation(path: Path) -> dict:
    if not path.exists():
        return {}
    text = path.read_text(encoding="utf-8", errors="replace")
    out = {}
    title = re.search(r"^title:\s*(.+)$", text, re.MULTILINE)
    if title:
        out["title"] = " ".join(title.group(1).strip().strip("'").split())
    for key in ("doi", "url", "year", "version"):
        m = re.search(rf"^{key}:\s*(.+)$", text, re.MULTILINE)
        if m:
            out[key] = m.group(1).strip().strip("'")
    n_authors = len(re.findall(r"^- family-names:", text, re.MULTILINE))
    if n_authors:
        out["n_authors"] = n_authors
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="write a local provenance sheet")
    ap.add_argument("--root", default=".", help="repository root")
    ap.add_argument("--out", default="out/data_provenance.md")
    args = ap.parse_args(argv)
    root = Path(args.root).resolve()

    L = ["# Data and toolchain provenance (verified locally, offline)", ""]
    L.append("Generated by `recordcheck.provenance`; every hash below was recomputed from the file in "
             "this workspace, not copied from a description.")
    L.append("")
    L.append("## Inputs present")
    L.append("")
    L.append("| file | bytes | sha256 | role |")
    L.append("|---|---:|---|---|")
    present = {}
    for rel, role in INPUTS:
        p = root / rel
        if p.exists():
            h = sha256(p)
            present[rel] = {"bytes": p.stat().st_size, "sha256": h, "role": role}
            L.append(f"| `{rel}` | {p.stat().st_size:,} | `{h}` | {role} |")
        else:
            L.append(f"| `{rel}` | — | — | **absent** ({role}) |")
    L.append("")
    cite = read_citation(root / "data/known/peripato/Vperipato-ade2541-78f685a/CITATION.cff")
    if cite:
        L.append("## Citation details read from the release's own CITATION.cff")
        L.append("")
        L.append(f"- title: {cite.get('title', '?')}")
        if "n_authors" in cite:
            L.append(f"- authors listed: {cite['n_authors']}")
        L.append(f"- doi: {cite.get('doi', '?')}")
        L.append(f"- url: {cite.get('url', '?')}")
        L.append(f"- year: {cite.get('year', '?')}")
        L.append("- publisher: Zenodo repository")
        L.append("")
        L.append("The release README states the data and R code belong to the manuscript "
                 "\"Over 10,000 Pre-Columbian earthworks are still hidden throughout Amazonia\" "
                 "(Science, DOI suffix `ade2541`). Any literature statement in the final report must be "
                 "the coordinator's, checked online; this sheet only records what the local files say.")
        L.append("")
    state = root / "checkpoint" / "state.json"
    if state.exists():
        try:
            s = json.loads(state.read_text(encoding="utf-8"))
            st = s.get("setup", {})
            L.append("## Download sources recorded by the coordinator (`checkpoint/state.json`)")
            L.append("")
            for key in ("known_sites", "footprints"):
                if key in st:
                    L.append(f"- {key}: {st[key].get('source', '?')} ({st[key].get('rows', '?')} rows)")
            if "positive_control" in st:
                pc = st["positive_control"]
                L.append(f"- positive control: transect {pc.get('transect')}, raw file "
                         f"`{pc.get('raw_path')}`, {pc.get('point_count')} points, EPSG:{pc.get('epsg')}")
            L.append("")
        except Exception as exc:  # noqa: BLE001
            L.append(f"(could not read checkpoint/state.json: {exc})")
            L.append("")

    L.append("## Toolchain")
    L.append("")
    L.append(f"- python {sys.version.split()[0]}")
    try:
        import numpy
        import pandas
        import pyproj

        L.append(f"- pyproj {pyproj.__version__} (PROJ {pyproj.proj_version_str}), numpy {numpy.__version__}, "
                 f"pandas {pandas.__version__}")
    except Exception as exc:  # noqa: BLE001
        L.append(f"- pyproj unavailable: {exc}")
    try:
        import pyreadr

        L.append(f"- pyreadr {getattr(pyreadr, '__version__', '?')} (primary .rds backend)")
    except Exception:
        L.append("- pyreadr not importable: the record check falls back to R or to the bundled reader")
    L.append("- no GDAL, PDAL, lastools, rasterio or network `pip install` in this VM; the record check "
             "needs none of them")
    L.append("")
    L.append("## Verified object-level facts")
    L.append("")
    L.append("These come from `out/known_table_audit.md`, `out/transect_proximity_validation.txt` and "
             "`out/audit_real_0414_verification.txt`:")
    L.append("")
    L.append("- `Earthworks.rds` holds **961** records with exactly three columns (`Longitude`, `Latitude`, "
             "`Database`); three independent readers agree row for row, and the coordinator's "
             "`data/known/earthworks.csv` is an exact copy (max |Δlat| 1.8e-15).")
    L.append("- register labels are compound (nine distinct strings); 283 rows are `Multiple: (...)` and "
             "24 are `TREES/INPE`.")
    L.append("- 76 record pairs lie within 1 m of each other (75 across different labels); single-linkage "
             "clustering gives 756 places at 500 m, 559 at 2 km, 339 at 5 km.")
    L.append("- the 24 `TREES/INPE` records have no other-register record within 500 m (min 1620 m, median "
             "14.3 km), consistent with the brief's warning that those positions may be displaced.")
    L.append("- the footprint layer has **901** polygons in EPSG:5880 whose ids match the coordinator's "
             "`transect_ids.json` exactly; the DBF `epsg` column is each tile's own LAZ CRS "
             "(EPSG:31973–31983), *not* the footprint CRS.")
    L.append("- transect **0414** contains the published control geoglyph: record 746 "
             "`Multiple: (Amazon Arch | CNSA | PAST)` lies inside the footprint, and `TREES/INPE` records "
             "657/658/659 lie 520.7/233.6/100.6 m from its boundary.")
    L.append("")
    L.append("## Dead ends checked (do not repeat)")
    L.append("")
    L.append("- `Database/IPP_ModelOutput.rds` (the published predictive-model output) is an **S4 object of "
             "class `bayesPO_fit`**. `pyreadr` reports no readable objects; base R refuses to load it "
             "without the `bayesPO` package, which is not installed and cannot be installed offline. The "
             "predictive-probability layer is therefore unavailable, and no candidate may be scored with it.")
    L.append("- `Database/GLM_RegressionOutput.zip` contains only `GLMReg_SpeciesAbundance.rds` and "
             "`GLMReg_SpeciesOcurrence.rds` (domesticated-species models), not earthwork predictions.")
    L.append("")
    L.append("## Reproduce this sheet")
    L.append("")
    L.append("```bash")
    L.append("PY=.venv/bin/python; RC=.ultramath/smwduocxj/m7")
    L.append("PYTHONPATH=$RC $PY -m recordcheck.provenance --root . --out $RC/out/data_provenance.md")
    L.append("```")
    L.append("")

    out = root / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L[:14]))
    print(f"... wrote {out} ({len(L)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
