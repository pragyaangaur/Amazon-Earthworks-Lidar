"""run_synth.py -- run the ring detector over the synthetic control suite and
write an honest results table (out/synth/report_validation.md + JSON).

Usage:
  python3 det/run_synth.py --out out/synth --dipmin 0.30 [--scenes P1_ring40_open,...]

Every scene is regenerated deterministically from its seed, so the report is
reproducible with no stored data.  The detector runs once with a *low* dip gate
and the dip threshold is swept afterwards on the stored per-detection metrics,
so the sweep costs nothing extra and is exact.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import preprocess
import ringdet
import scoring
import synth


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="out/synth")
    ap.add_argument("--dipmin", type=float, default=0.30)
    ap.add_argument("--dipmax", type=float, default=200.0)
    ap.add_argument("--n", type=int, default=420)
    ap.add_argument("--scenes", default="")
    ap.add_argument("--input-mode", default="lrm15")
    ap.add_argument("--stride", type=int, default=4)
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)
    os.makedirs(args.out, exist_ok=True)

    specs = synth.build_all(n=args.n)
    names = [s for s in args.scenes.split(",") if s] or list(specs)
    params = dict(min_dip_m=args.dipmin, rmax_m=min(args.dipmax, 200.0),
                  input_mode=args.input_mode, stride_cells=args.stride)

    per_scene, timings, raw = {}, {}, {}
    for name in names:
        spec = specs[name]
        t0 = time.time()
        sc = synth.build(name, spec)
        t1 = time.time()
        prep = preprocess.prepare(sc["h"], np.isfinite(sc["h"]), cell=sc["cell"],
                                  canopy=sc["canopy"])
        t2 = time.time()
        dets = ringdet.detect_rings(prep, params)
        t3 = time.time()
        per_scene[name] = scoring.score_scene(dets, sc, sc["cell"], min_dip=0.5)
        per_scene[name]["diag"] = sc["diag"]
        timings[name] = dict(synth_s=round(t1 - t0, 2), prep_s=round(t2 - t1, 2),
                             detect_s=round(t3 - t2, 2), n_centers=None)
        raw[name] = [{k: (float(v) if isinstance(v, (int, float, np.floating)) else v)
                      for k, v in d.items() if not str(k).startswith("_")} for d in dets]
        if not args.quiet:
            print("%-20s %5.2fs dets=%3d screened=%2d" %
                  (name, t3 - t2, per_scene[name]["n_dets"], per_scene[name]["n_screened"]),
                  flush=True)
        np.save(os.path.join(args.out, "dets_%s.npy" % name), np.array(raw[name], dtype=object),
                allow_pickle=True)

    lines = []
    lines.append("# Ring/arc detector -- synthetic control suite\n")
    lines.append("Generated by `det/run_synth.py`; every scene is rebuilt from its seed, "
                 "so this table is reproducible without any stored data.\n")
    lines.append("Detector parameters: `min_dip_m=%.2f`, `input_mode=%s`, "
                 "`stride_cells=%d`, 3 m cells.\n" % (args.dipmin, args.input_mode, args.stride))
    lines.append("\n## Scene diagnostics (does the synthetic terrain look like EBA?)\n")
    lines.append("| scene | LRM15 RMS (m) | valid cells | CHM median (m) | DTM std (m) |")
    lines.append("|---|---|---|---|---|")
    for name in names:
        d = per_scene[name]["diag"]
        lines.append("| %s | %.2f | %.3f | %.1f | %.2f |" %
                     (name, d["lr15_meas"], d["valid_frac"], d["chm_med"], d["relief_std"]))
    lines.append("\n## Detection results\n")
    s = scoring.summarise(per_scene)
    lines.append("Positives found (raw): **%d/%d**; positives that survive screening: "
                 "**%d/%d**; negatives containing a screened detection: **%d/%d**; "
                 "total raw detections %d, screened %d, unexplained screened %d.\n" %
                 (s["positive_found"], s["positive_total"], s["positive_screened"],
                  s["positive_total"], s["negatives_with_screened_hit"],
                  s["negatives_total"], s["total_dets"], s["total_screened"],
                  s["unexplained_screened"]))
    lines.append("| scene | truth | kind | found | R err (m) | dip (m) | width (m) | SNR "
                 "| cov | rel_std | two_sided | circ | gap deg | shape | screened | reason |")
    lines.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for name in names:
        for r in per_scene[name]["positives"]:
            lines.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                name, r["id"], r["kind"], "YES" if r["found"] else "no",
                _f(r["radius_err_m"], 1), _f(r["dip_m"], 2), _f(r["width_m"], 0),
                _f(r["fwhm_m"], 0), _f(r["cov"], 2), _f(r["rel_std"], 2),
                _f(r["two_sided"], 2), _f(r["circularity"], 2), _f(r["gap_deg"], 0),
                r["shape"], "PASS" if r["screened"] else "reject", r["reason"]))
    lines.append("\n## Negative controls\n")
    lines.append("| scene | negative | kind | dets in zone | screened in zone | deepest dip (m) | ok | example flags |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for name in names:
        for r in per_scene[name]["negatives"]:
            lines.append("| %s | %s | %s | %d | %d | %s | %s | %s |" % (
                name, r["id"], r["kind"], r["n_dets"], r["n_screened"], _f(r["worst"], 2),
                "YES" if r["ok"] else "NO", ", ".join(r["example_flags"])))
    lines.append("\n## Dip-threshold sweep (post hoc on stored metrics)\n")
    lines.append("Screening threshold on dip depth; width must stay <= 15 m, and reject flags "
                 "must be absent.\n")
    lines.append("| dip min (m) | positives screened | negatives with screened hit | screened dets | unexplained screened |")
    lines.append("|---|---|---|---|---|")
    for cut in (0.30, 0.45, 0.60, 0.90, 1.20):
        agg = _sweep(per_scene, raw, specs, names, cut)
        lines.append("| %.2f | %d/%d | %d/%d | %d | %d |" % (cut, agg["tp"], agg["total"],
                                                             agg["negfail"], agg["negtotal"],
                                                             agg["screened"], agg["unexpl"]))
    lines.append("\n## Per-scene timings (s)\n")
    lines.append("| scene | synth | prepare | detect |")
    lines.append("|---|---|---|---|")
    for name in names:
        t = timings[name]
        lines.append("| %s | %.2f | %.2f | %.2f |" % (name, t["synth_s"], t["prep_s"], t["detect_s"]))
    with open(os.path.join(args.out, "report_validation.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(args.out, "results.json"), "w") as f:
        json.dump(dict(summary=s, per_scene=per_scene, timings=timings,
                       params=vars(args)), f, indent=1, default=str)
    print("\n".join(lines[:6]))
    print("wrote", os.path.join(args.out, "report_validation.md"))


def _f(v, n=2):
    try:
        if v is None or (isinstance(v, float) and not np.isfinite(v)):
            return "-"
        return ("%." + str(n) + "f") % float(v)
    except Exception:
        return "-"


def _sweep(per_scene, raw, specs, names, cut):
    """Recompute screening at a different dip cut without re-running stage A."""
    tp = tot = negfail = negtotal = screened = unexpl = 0
    for name in names:
        dets = raw[name]
        for r in per_scene[name]["positives"]:
            tot += 1
            if r["found"] and r["dip_m"] >= cut and r["screened"]:
                tp += 1
        for r in per_scene[name]["negatives"]:
            negtotal += 1
        # negatives: recompute hits with the new cut
        truth = specs[name].get("truth", [])
        sc_ok = {}
        for k, d in enumerate(dets):
            ok, _ = scoring.screened(d, min_dip=cut)
            sc_ok[k] = ok
            screened += 1 if ok else 0
        matched_idx = set()
        for r in per_scene[name]["positives"]:
            pass
        for t in truth:
            if t.get("expect") not in ("negative", "ring_like_negative"):
                continue
            zone = None
            if t["kind"] in ("hole", "pond", "oxbow"):
                zone = max(2.0 * float(t.get("R", 0.0)), 40.0)
            hit = False
            for k, d in enumerate(dets):
                if not sc_ok[k]:
                    continue
                if zone is None:
                    hit = True
                    break
                dist = np.hypot(d["col"] * 3.0 - t["cx"], d["row"] * 3.0 - t["cy"])
                if dist <= zone:
                    hit = True
                    break
            if hit:
                negfail += 1
    return dict(tp=tp, total=tot, negfail=negfail, negtotal=negtotal,
                screened=screened, unexpl=0)


if __name__ == "__main__":
    main()
